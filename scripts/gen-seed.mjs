// Writes netlify/database/migrations/0002_seed.sql from Debbie's build: every product (the 44 mirrors on sale and the
// 4 homewares she hid), her delivery zones, pick-up details, discount codes and store settings.
// Customer-facing text (name, description, details, price, badge) is taken from the shop (store.js), so the
// live shop reads exactly as her preview did. Stock, supplier codes and SKUs come from her admin (admin-data.js).
// Run once: node scripts/gen-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readClientData } from './lib-client-data.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { admin, catalogue } = readClientData(path.join(root, 'public'));

const q = (v) => (v == null ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'");
const j = (v) => q(JSON.stringify(v)) + '::jsonb';
const n = (v) => (v == null || v === '' ? 'NULL' : String(parseInt(v, 10)));

const rows = [];
admin.products.forEach((p, i) => {
  const c = catalogue.find((x) => x.slug === p.slug) || {};
  rows.push({
    slug: p.slug, title: c.name || p.title, category: c.category || p.category, price: c.price_cents ?? p.price,
    compare_at: p.compareAt, cost: p.cost, status: p.status || 'active', stock: p.stock, low_at: p.lowAt,
    supplier_code: p.supplierCode || '', sku: p.sku || '', weight: p.weight || '', size: p.size || '',
    badge: c.badge != null ? c.badge : p.badge || '', both_ways: !!p.bothWays, images: p.images || [],
    description: c.desc != null ? c.desc : p.desc || '', specs: c.specs || p.specs || [], sort_order: i
  });
});
// Products in the shop's list that aren't in her admin: the homewares, hidden from the shop by category.
catalogue.filter((c) => !admin.products.some((p) => p.slug === c.slug)).forEach((c, i) => {
  rows.push({
    slug: c.slug, title: c.name, category: c.category, price: c.price_cents, compare_at: null, cost: null,
    status: 'archived', stock: null, low_at: null, supplier_code: '', sku: '', weight: '', size: '',
    badge: c.badge || '', both_ways: false, images: [], description: c.desc || '', specs: c.specs || [], sort_order: 1000 + i
  });
});

let sql = '-- Generated by scripts/gen-seed.mjs from public/js/admin-data.js and public/js/store.js. Do not edit by hand.\n\n';
sql += 'INSERT INTO products (slug, title, category, price, compare_at, cost, status, stock, low_at, supplier_code, sku, weight, size, badge, both_ways, images, description, specs, sort_order) VALUES\n';
sql += rows.map((r) => '(' + [q(r.slug), q(r.title), q(r.category), n(r.price), n(r.compare_at), n(r.cost), q(r.status), n(r.stock), n(r.low_at),
  q(r.supplier_code), q(r.sku), q(r.weight), q(r.size), q(r.badge), r.both_ways ? 'true' : 'false', j(r.images), q(r.description), j(r.specs), r.sort_order].join(', ') + ')').join(',\n') + ';\n\n';

sql += 'INSERT INTO discount_codes (code, type, value, min_spend, first_order_only, starts, ends, usage_limit, active, sort_order) VALUES\n';
sql += admin.discounts.map((d, i) => '(' + [q(d.code.toUpperCase()), q(d.type || 'pct'), n(d.value ?? d.pct), n(d.minSpend || 0), d.firstOrderOnly ? 'true' : 'false',
  q(d.starts), q(d.ends || d.expires), n(d.limit), d.active === false ? 'false' : 'true', i].join(', ') + ')').join(',\n') + ';\n\n';

sql += 'INSERT INTO settings (key, value) VALUES\n';
sql += "('store', " + j(admin.settings) + '),\n';
sql += "('shipping', " + j(admin.shipping) + ');\n';

const out = path.join(root, 'netlify/database/migrations/0002_seed.sql');
fs.writeFileSync(out, sql);
console.log('Wrote ' + path.relative(root, out) + ': ' + rows.length + ' products (' + rows.filter((r) => r.status === 'active').length + ' active), ' + admin.discounts.length + ' discount code(s).');
