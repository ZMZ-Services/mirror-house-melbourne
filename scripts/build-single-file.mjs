// Builds single-file/mirror-house-melbourne.html: the whole site (home, product, checkout,
// room visualiser, dashboard) in one HTML file that runs without the Worker or D1.
//   node scripts/build-single-file.mjs
// Photos load from the live site so the file stays small enough to edit with Claude.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LIVE = 'https://mirror-house-melbourne.zarko-ddc.workers.dev';
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

// Inside <script type="text/html"> blocks, "</script" must be written "<\/script".
const store = (text) => text.replace(/<\/script/gi, '<\\/script');

const pages = {
  home: read('public/index.html'),
  product: read('public/product.html'),
  checkout: read('public/checkout.html'),
  room: read('public/visualiser.html'),
  dashboard: read('public/admin-dashboard.html'),
};
const shared = {
  'theme-css': read('public/css/theme.css'),
  'store-js': read('public/js/store.js'),
  'visualiser-js': read('public/js/visualiser.js'),
  'local-api-js': read('single-file/local-api.js'),
};
for (const [name, code] of Object.entries(shared)) {
  if (/<\/script/i.test(code)) throw new Error(`${name} contains "</script" and can't be embedded`);
}

const block = (id, type, text, label) =>
  `\n<!-- ${'='.repeat(10)} ${label} ${'='.repeat(10)} -->\n<script type="${type}" id="${id}">\n${text.trim()}\n</script>\n`;

const html = `<!DOCTYPE html>
<html lang="en-AU">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<title>Mirror House Melbourne</title>
<!--
  MIRROR HOUSE MELBOURNE: the whole site in one file.

  How this file is organised (edit the blocks, not the router at the bottom):
    PAGE blocks      one per page, each a normal HTML page:
                       page-home (shop front), page-product, page-checkout,
                       page-room (try it in your room), page-dashboard (back of house)
    SHARED blocks    used by several pages, written once:
                       shared-theme-css (shop styles), shared-store-js (catalogue, bag, checkout),
                       shared-visualiser-js (3D room), shared-local-api-js (pretend database)
    ROUTER           the small script at the very bottom that shows the right page.

  Rules for editing:
    - Inside a block, write "<\\/script>" instead of "</script>" (the block itself is a script tag).
    - Links like /product.html?slug=..., /checkout.html, /visualiser, /admin-dashboard.html and /#section
      keep working: the router opens the matching page block.
    - Photos load from ${LIVE}/images/. To swap a photo, change its URL.
    - Orders, signups and stock are saved in this browser only (shared-local-api-js), not the live database.

  Generated by scripts/build-single-file.mjs from the live site's source.
-->
<style>
  html, body { margin: 0; height: 100%; background: #F7F3ED; }
  #page { position: fixed; inset: 0; width: 100%; height: 100%; border: 0; display: block; background: #F7F3ED; }
</style>
</head>
<body>
<iframe id="page" title="Mirror House Melbourne"></iframe>
${block('page-home', 'text/html', store(pages.home), 'PAGE: HOME / SHOP FRONT (index.html)')}
${block('page-product', 'text/html', store(pages.product), 'PAGE: PRODUCT (product.html?slug=...)')}
${block('page-checkout', 'text/html', store(pages.checkout), 'PAGE: CHECKOUT (checkout.html)')}
${block('page-room', 'text/html', store(pages.room), 'PAGE: TRY IT IN YOUR ROOM (visualiser.html)')}
${block('page-dashboard', 'text/html', store(pages.dashboard), 'PAGE: BACK OF HOUSE DASHBOARD (admin-dashboard.html)')}
${block('shared-theme-css', 'text/plain', shared['theme-css'], 'SHARED: SHOP STYLES (css/theme.css)')}
${block('shared-store-js', 'text/plain', shared['store-js'], 'SHARED: SHOP SCRIPT (js/store.js)')}
${block('shared-visualiser-js', 'text/plain', shared['visualiser-js'], 'SHARED: 3D ROOM SCRIPT (js/visualiser.js)')}
${block('shared-local-api-js', 'text/plain', shared['local-api-js'], 'SHARED: PRETEND DATABASE (stands in for the Cloudflare Worker + D1)')}

<!-- ========== ROUTER ========== -->
<script>
(function () {
  'use strict';
  var LIVE = ${JSON.stringify(LIVE)};
  var frame = document.getElementById('page');
  function text(id) { return document.getElementById(id).textContent.replace(/<\\\\\\/script/gi, '</' + 'script'); }

  // Which page block a path opens.
  function pageFor(pathname) {
    var p = pathname.replace(/\\/+$/, '').replace(/\\.html$/, '') || '/';
    if (p === '/product') return 'product';
    if (p === '/checkout') return 'checkout';
    if (p === '/visualiser') return 'room';
    if (p === '/admin-dashboard' || p === '/admin') return 'dashboard';
    return 'home';
  }

  // Runs first inside every page: routes clicks on site links through the router.
  function navScript(query, hash) {
    return '<script>window.MH_ROUTE_QUERY=' + JSON.stringify(query) + ';window.MH_ROUTE_HASH=' + JSON.stringify(hash) + ';' +
      'window.addEventListener("click",function(e){if(e.defaultPrevented)return;var a=e.target.closest&&e.target.closest("a[href]");if(!a)return;' +
      'var h=a.getAttribute("href");if(/^(mailto|tel|sms|javascript):/i.test(h))return;' +
      'if(h.charAt(0)==="#"){e.preventDefault();var t=h.length>1&&document.getElementById(decodeURIComponent(h.slice(1)));if(t)t.scrollIntoView({behavior:"smooth"});else window.scrollTo({top:0,behavior:"smooth"});return;}' +
      'if(h.charAt(0)==="/"||h.indexOf(' + JSON.stringify(LIVE) + ')===0){e.preventDefault();parent.MH.go(h.indexOf(' + JSON.stringify(LIVE) + ')===0?h.slice(' + LIVE.length + '):h);}' +
      '});<' + '/script>';
  }

  function build(page, query, hash) {
    var doc = text('page-' + page);
    var head = '<base href="' + LIVE + '/">' + navScript(query, hash) + '<script>' + text('shared-local-api-js') + '<' + '/script>';
    doc = doc.replace(/<head>/i, '<head>' + head);
    doc = doc.replace(/<link rel="stylesheet" href="\\/css\\/theme\\.css">/, function () { return '<style>' + text('shared-theme-css') + '</style>'; });
    doc = doc.replace(/<script src="\\/js\\/store\\.js"><\\/script>/, function () { return '<script>' + text('shared-store-js') + '<' + '/script>'; });
    doc = doc.replace(/<script type="module" src="\\/js\\/visualiser\\.js"><\\/script>/, function () { return '<script type="module">' + text('shared-visualiser-js') + '<' + '/script>'; });
    return doc;
  }

  var current = null;
  function show(path) {
    var url;
    try { url = new URL(path || '/', LIVE); } catch (e) { url = new URL('/', LIVE); }
    var page = pageFor(url.pathname);
    var key = page + url.search;
    var hash = url.hash ? decodeURIComponent(url.hash.slice(1)) : '';
    if (key === current && frame.contentDocument) {
      var t = hash && frame.contentDocument.getElementById(hash);
      if (t) t.scrollIntoView({ behavior: 'smooth' }); else frame.contentWindow.scrollTo(0, 0);
      return;
    }
    current = key;
    frame.onload = function () {
      try {
        var d = frame.contentDocument;
        document.title = d.title || 'Mirror House Melbourne';
        var t = hash && d.getElementById(hash);
        if (t) t.scrollIntoView();
        frame.contentWindow.focus();
      } catch (e) { /* ignore */ }
    };
    frame.srcdoc = build(page, url.search, hash);
  }

  function routeFromHash() { return location.hash.length > 1 ? decodeURIComponent(location.hash.slice(1)) : '/'; }

  window.MH = {
    go: function (path) {
      var token = '#' + encodeURI(path);
      if (location.hash === token) show(path);
      else location.hash = token;
    }
  };
  window.addEventListener('hashchange', function () { show(routeFromHash()); });
  // Keep the bag badge in step when another page changes it.
  window.addEventListener('storage', function () { /* each page listens itself */ });
  show(routeFromHash());
})();
</script>
</body>
</html>
`;

writeFileSync(join(ROOT, 'single-file/mirror-house-melbourne.html'), html);
console.log(`single-file/mirror-house-melbourne.html: ${(html.length / 1024).toFixed(0)} KB`);
